package com.itwastall.advancement;

import com.itwastall.ItWasTall;
import com.itwastall.director.Director;
import com.itwastall.world.ItWasTallState;
import net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents;
import net.fabricmc.fabric.api.networking.v1.PlayerLookup;
import net.minecraft.advancement.AdvancementEntry;
import net.minecraft.advancement.AdvancementProgress;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.network.ServerPlayerEntity;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * The "It Was Tall" tab of the advancements screen (L). The advancements live in
 * data/itwastall/advancement (generated by tools/gen_advancements.py); almost all of them use the
 * "minecraft:impossible" trigger and are granted from the event code through {@link #grant}.
 * The structure ones (explorer / cartographer) use vanilla location triggers.
 */
public final class Achievements {
    /** Shared-journal books needed for "Librarian". */
    public static final int LIBRARIAN_BOOKS = 10;

    private Achievements() {}

    public static void init() {
        // states that every player on the server shares: the phase, the stage, the shared journal
        ServerTickEvents.END_SERVER_TICK.register(server -> {
            if (server.getTicks() % 40 != 0) return;
            int phase = Director.phase(), stage = Director.stageIndex();
            int books = ItWasTallState.getOrCreate(server).sharedBooks().size();
            for (ServerPlayerEntity p : PlayerLookup.all(server)) {
                if (phase >= 1) grant(p, "it_joined");
                if (stage >= 3) grant(p, "stage_3");
                if (stage >= 5) grant(p, "it_was_tall");
                if (books >= LIBRARIAN_BOOKS) grant(p, "librarian");
            }
        });
    }

    /** Grants the advancement itwastall:{id} to that player (all of its criteria). Safe to call any number of times. */
    public static void grant(@Nullable ServerPlayerEntity player, String id) {
        if (player == null) return;
        MinecraftServer server = player.getServer();
        if (server == null) return;
        try {
            AdvancementEntry entry = server.getAdvancementLoader().get(ItWasTall.id(id));
            if (entry == null) return;
            AdvancementProgress progress = player.getAdvancementTracker().getProgress(entry);
            if (progress.isDone()) return;
            List<String> missing = new ArrayList<>();
            for (String criterion : progress.getUnobtainedCriteria()) missing.add(criterion);
            for (String criterion : missing) player.getAdvancementTracker().grantCriterion(entry, criterion);
        } catch (RuntimeException e) {
            ItWasTall.LOGGER.debug("Could not grant advancement {}: {}", id, e.toString());
        }
    }

    /** A finished task: "Do As It Says" plus the one for that task kind (task_stay_inside, ...). */
    public static void taskCompleted(ServerPlayerEntity player, String kind) {
        grant(player, "task_done");
        grant(player, "task_" + kind.toLowerCase(Locale.ROOT));
    }
}
