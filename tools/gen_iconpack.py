def icon(name, grid):
    rows = [r for r in grid.strip("\n").split("\n")]
    assert len(rows) == 16, (name, len(rows))
    for r in rows:
        assert len(r) == 16, (name, r, len(r))
        for ch in r:
            assert ch == "." or ch in PAL, (name, ch)
    ICONS[name] = rows


